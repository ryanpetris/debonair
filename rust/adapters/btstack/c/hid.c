// Generated by build.rs from keyboard.gatt, mouse.gatt and combined.gatt.
extern const uint8_t *const debonair_db_keyboard;
extern const uint8_t *const debonair_db_mouse;
extern const uint8_t *const debonair_db_combined;
extern const uint16_t debonair_name_handle;
extern const uint16_t debonair_service_changed_handle;
extern const uint16_t debonair_service_changed_configuration_handle;
extern const uint16_t debonair_database_hash_handle;

#define NAME_BYTES 29
#define DESCRIPTOR_BYTES 512
// How long a Target may stay connected without encrypting. Pairing with a passkey needs time to
// type it.
#define UNENCRYPTED_PAIRING_MS 60000
#define UNENCRYPTED_MS 20000

static void *context;
static debonair_emit emit;
static char name[NAME_BYTES];
static uint16_t name_length;
static uint8_t descriptor[DESCRIPTOR_BYTES];
static char manufacturer[32];
static char model[65];
static char firmware[48];
static hids_device_report_t reports[5];
static uint16_t appearance;
static uint8_t advertising[31];
static uint8_t scan_response[31];
static hci_con_handle_t connection = HCI_CON_HANDLE_INVALID;
static bool encrypted;
static bool pairing;
static bool passkey_mode;
static bool send_requested;
static uint8_t leds;
static uint8_t feature;
static uint16_t service_changed_configuration;
static uint8_t last_keyboard[8];
static uint8_t last_mouse[9];
static uint8_t last_consumer[4];
static btstack_packet_callback_registration_t hci_registration;
static btstack_packet_callback_registration_t sm_registration;
static btstack_timer_source_t encryption_timer;
static btstack_context_callback_registration_t service_changed;

static void send_event(uint8_t kind, uint8_t code, uint8_t report_id, const uint8_t *address,
                       const uint8_t *data, uint16_t length) {
    debonair_event event = {
        .kind = kind, .code = code, .report_id = report_id, .entry = -1, .length = length, .data = data,
    };
    if (address) memcpy(event.address, address, 6);
    emit(context, &event);
}

// Keeps whole UTF-8 characters when a name is shortened.
static uint16_t utf8_prefix(const char *text, uint16_t length, uint16_t limit) {
    if (length <= limit) return length;
    while (limit > 0 && ((uint8_t)text[limit] & 0xc0) == 0x80) limit--;
    return limit;
}

static void update_advertising(void) {
    uint8_t at = 0;
    advertising[at++] = 2;
    advertising[at++] = BLUETOOTH_DATA_TYPE_FLAGS;
    // Discoverable only while pairing. BR/EDR is not supported.
    advertising[at++] = pairing ? 0x06 : 0x04;
    advertising[at++] = 3;
    advertising[at++] = BLUETOOTH_DATA_TYPE_APPEARANCE;
    advertising[at++] = appearance & 0xff;
    advertising[at++] = appearance >> 8;
    advertising[at++] = 3;
    advertising[at++] = BLUETOOTH_DATA_TYPE_COMPLETE_LIST_OF_16_BIT_SERVICE_CLASS_UUIDS;
    advertising[at++] = ORG_BLUETOOTH_SERVICE_HUMAN_INTERFACE_DEVICE & 0xff;
    advertising[at++] = ORG_BLUETOOTH_SERVICE_HUMAN_INTERFACE_DEVICE >> 8;
    uint16_t shown = utf8_prefix(name, name_length, sizeof advertising - at - 2);
    advertising[at++] = shown + 1;
    advertising[at++] = shown == name_length ? BLUETOOTH_DATA_TYPE_COMPLETE_LOCAL_NAME
                                             : BLUETOOTH_DATA_TYPE_SHORTENED_LOCAL_NAME;
    memcpy(&advertising[at], name, shown);
    at += shown;
    gap_advertisements_set_data(at, advertising);

    scan_response[0] = name_length + 1;
    scan_response[1] = BLUETOOTH_DATA_TYPE_COMPLETE_LOCAL_NAME;
    memcpy(&scan_response[2], name, name_length);
    gap_scan_response_set_data(name_length + 2, scan_response);
}

static uint16_t att_read(hci_con_handle_t handle, uint16_t attribute, uint16_t offset, uint8_t *buffer,
                         uint16_t size) {
    (void)handle;
    if (attribute == debonair_name_handle) {
        return att_read_callback_handle_blob((const uint8_t *)name, name_length, offset, buffer, size);
    }
    if (attribute == debonair_service_changed_configuration_handle) {
        return att_read_callback_handle_little_endian_16(service_changed_configuration, offset, buffer, size);
    }
    return 0;
}

// The ATT server saves a paired Target's subscriptions and replays them here on reconnection.
static int att_write(hci_con_handle_t handle, uint16_t attribute, uint16_t mode, uint16_t offset,
                     uint8_t *buffer, uint16_t size) {
    (void)handle;
    (void)offset;
    if (mode != ATT_TRANSACTION_MODE_NONE) return 0;
    if (attribute == debonair_service_changed_configuration_handle && size >= 2) {
        service_changed_configuration = little_endian_read_16(buffer, 0);
    }
    return 0;
}

static void get_report(hci_con_handle_t handle, hid_report_type_t type, uint16_t id, uint16_t size,
                       uint8_t *out) {
    (void)handle;
    memset(out, 0, size);
    const uint8_t *source = NULL;
    uint16_t length = 0;
    if (type == HID_REPORT_TYPE_FEATURE) {
        source = &feature;
        length = 1;
    } else if (type == HID_REPORT_TYPE_OUTPUT) {
        source = &leds;
        length = 1;
    } else if (id == 1) {
        source = last_keyboard;
        length = sizeof last_keyboard;
    } else if (id == 2) {
        source = last_mouse;
        length = sizeof last_mouse;
    } else if (id == 3) {
        source = last_consumer;
        length = sizeof last_consumer;
    }
    if (source) memcpy(out, source, btstack_min(length, size));
}

static void emit_address(uint8_t kind, uint8_t type, const uint8_t *address) {
    send_event(kind, type, 0, address, NULL, 0);
}

static int bond_index(void) {
    return connection == HCI_CON_HANDLE_INVALID ? -1 : sm_le_device_index(connection);
}

/** Remembers the feature report for a paired Target, which sets it only when it first sees the
 * device: Windows and Linux keep the HID device, and its multipliers, across reconnections. */
static void save_feature(void) { debonair_bonds_set_feature(bond_index(), feature); }

static const uint8_t *database_hash(void) {
    uint16_t length = 0;
    const uint8_t *hash = gatt_server_get_const_value_for_handle(debonair_database_hash_handle, &length);
    return length == 16 ? hash : NULL;
}

static void save_database(void) {
    const uint8_t *hash = database_hash();
    if (hash) debonair_bonds_set_database(bond_index(), hash, 16);
}

static void send_service_changed(void *context) {
    (void)context;
    if (connection == HCI_CON_HANDLE_INVALID) return;
    static const uint8_t range[] = {0x01, 0x00, 0xff, 0xff};
    // The database is saved once the Target confirms, so an unconfirmed change is sent again.
    att_server_indicate(connection, debonair_service_changed_handle, range, sizeof range);
}

/** Restores what a paired Target set before, and tells it to rediscover services when this
 * firmware's database differs from the one it cached. */
static void restore_bond(void) {
    int index = bond_index();
    if (index < 0) return;
    if (debonair_bonds_feature(index, &feature)) {
        send_event(DEBONAIR_EVENT_FEATURE, 0, 2, NULL, &feature, 1);
    }
    const uint8_t *hash = database_hash();
    if (hash && !debonair_bonds_database_is(index, hash, 16)) {
        service_changed.callback = send_service_changed;
        att_server_request_to_send_indication(&service_changed, connection);
    }
}

static void encryption_timeout(btstack_timer_source_t *timer) {
    (void)timer;
    if (connection != HCI_CON_HANDLE_INVALID && !encrypted) gap_disconnect(connection);
}

static void refuse(hci_con_handle_t handle) {
    sm_bonding_decline(handle);
    // Outside pairing, a Target that cannot pair would otherwise hold the only connection.
    if (!pairing) gap_disconnect(handle);
}

static void handler(uint8_t packet_type, uint16_t channel, uint8_t *packet, uint16_t size) {
    (void)channel;
    (void)size;
    if (packet_type != HCI_EVENT_PACKET) return;
    bd_addr_t address;
    hci_con_handle_t handle;
    switch (hci_event_packet_get_type(packet)) {
    case BTSTACK_EVENT_STATE:
        if (btstack_event_state_get_state(packet) == HCI_STATE_WORKING) {
            send_event(DEBONAIR_EVENT_READY, 0, 0, NULL, NULL, 0);
        }
        break;
    case HCI_EVENT_META_GAP:
        if (hci_event_gap_meta_get_subevent_code(packet) != GAP_SUBEVENT_LE_CONNECTION_COMPLETE) break;
        if (gap_subevent_le_connection_complete_get_status(packet) != ERROR_CODE_SUCCESS) break;
        if (gap_subevent_le_connection_complete_get_role(packet) != HCI_ROLE_SLAVE) break;
        connection = gap_subevent_le_connection_complete_get_connection_handle(packet);
        encrypted = false;
        send_requested = false;
        leds = 0;
        feature = 0;
        service_changed_configuration = 0;
        btstack_run_loop_set_timer_handler(&encryption_timer, encryption_timeout);
        btstack_run_loop_set_timer(&encryption_timer, pairing ? UNENCRYPTED_PAIRING_MS : UNENCRYPTED_MS);
        btstack_run_loop_add_timer(&encryption_timer);
        gap_subevent_le_connection_complete_get_peer_address(packet, address);
        // A Target encrypts by itself: a paired one on reconnecting, a new one when it first reads
        // a report and finds it needs encryption. A Security Request here would make BTstack's ATT
        // server hold every request until a pairing completes, even for a Target that only
        // re-encrypts.
        emit_address(DEBONAIR_EVENT_CONNECTED,
                     gap_subevent_le_connection_complete_get_peer_address_type(packet), address);
        break;
    case HCI_EVENT_DISCONNECTION_COMPLETE:
        if (hci_event_disconnection_complete_get_connection_handle(packet) != connection) break;
        connection = HCI_CON_HANDLE_INVALID;
        encrypted = false;
        send_requested = false;
        btstack_run_loop_remove_timer(&encryption_timer);
        send_event(DEBONAIR_EVENT_DISCONNECTED, 0, 0, NULL, NULL, 0);
        break;
    case HCI_EVENT_ENCRYPTION_CHANGE:
    case HCI_EVENT_ENCRYPTION_CHANGE_V2:
        if (hci_event_encryption_change_get_connection_handle(packet) != connection) break;
        if (hci_event_encryption_change_get_status(packet) != ERROR_CODE_SUCCESS) break;
        encrypted = hci_event_encryption_change_get_encryption_enabled(packet) != 0;
        if (encrypted) {
            btstack_run_loop_remove_timer(&encryption_timer);
            send_event(DEBONAIR_EVENT_SECURED, 0, 0, NULL, NULL, 0);
            restore_bond();
            // 15 ms, within Apple's accessory rules, with a 3 s supervision timeout.
            gap_request_connection_parameter_update(connection, 12, 12, 0, 300);
        }
        break;
    case SM_EVENT_PAIRING_STARTED:
        // Give a pairing time to finish, such as for typing a passkey.
        if (sm_event_pairing_started_get_handle(packet) != connection || encrypted) break;
        btstack_run_loop_remove_timer(&encryption_timer);
        btstack_run_loop_set_timer(&encryption_timer, UNENCRYPTED_PAIRING_MS);
        btstack_run_loop_add_timer(&encryption_timer);
        break;
    case SM_EVENT_JUST_WORKS_REQUEST:
        // With passkey security, a Target that cannot show a passkey is refused.
        handle = sm_event_just_works_request_get_handle(packet);
        if (pairing && !passkey_mode) sm_just_works_confirm(handle);
        else refuse(handle);
        break;
    case SM_EVENT_NUMERIC_COMPARISON_REQUEST:
        // The adapter shows nothing to compare, so this method is never offered; refuse it.
        refuse(sm_event_numeric_comparison_request_get_handle(packet));
        break;
    case SM_EVENT_PASSKEY_INPUT_NUMBER:
        handle = sm_event_passkey_input_number_get_handle(packet);
        if (pairing && handle == connection) send_event(DEBONAIR_EVENT_PASSKEY_REQUEST, 0, 0, NULL, NULL, 0);
        else refuse(handle);
        break;
    case SM_EVENT_PAIRING_COMPLETE: {
        if (sm_event_pairing_complete_get_handle(packet) != connection) break;
        bool success = sm_event_pairing_complete_get_status(packet) == ERROR_CODE_SUCCESS;
        if (success && passkey_mode && !gap_authenticated(connection)) {
            // A pairing without the passkey never stays in passkey mode.
            sm_event_pairing_complete_get_address(packet, address);
            gap_delete_bonding((bd_addr_type_t)sm_event_pairing_complete_get_addr_type(packet), address);
            gap_disconnect(connection);
            success = false;
        }
        if (success && bond_index() < 0) {
            // HID over GATT needs a bond, so a pairing that keeps none is refused.
            gap_disconnect(connection);
            success = false;
        }
        debonair_event event = {.kind = DEBONAIR_EVENT_PAIRING_COMPLETE, .code = success, .entry = -1};
        if (success) {
            // Pairing again without distributing keys still makes the Target the newest pairing.
            debonair_bonds_paired(bond_index());
            // The Target discovered this firmware's database while pairing.
            save_database();
            save_feature();
            event.entry = (int8_t)bond_index();
        }
        emit(context, &event);
        send_event(DEBONAIR_EVENT_TARGETS_CHANGED, 0, 0, NULL, NULL, 0);
        break;
    }
    case SM_EVENT_IDENTITY_RESOLVING_SUCCEEDED:
        if (sm_event_identity_resolving_succeeded_get_handle(packet) != connection) break;
        sm_event_identity_resolving_succeeded_get_identity_address(packet, address);
        emit_address(DEBONAIR_EVENT_IDENTIFIED,
                     sm_event_identity_resolving_succeeded_get_identity_addr_type(packet), address);
        break;
    case SM_EVENT_IDENTITY_CREATED:
        if (sm_event_identity_created_get_handle(packet) != connection) break;
        sm_event_identity_created_get_identity_address(packet, address);
        emit_address(DEBONAIR_EVENT_IDENTIFIED, sm_event_identity_created_get_identity_addr_type(packet),
                     address);
        break;
    case HCI_EVENT_HIDS_META:
        switch (hci_event_hids_meta_get_subevent_code(packet)) {
        case HIDS_SUBEVENT_CAN_SEND_NOW:
            send_requested = false;
            send_event(DEBONAIR_EVENT_CAN_SEND, 0, 0, NULL, NULL, 0);
            break;
        case HIDS_SUBEVENT_PROTOCOL_MODE:
            send_event(DEBONAIR_EVENT_PROTOCOL_MODE, hids_subevent_protocol_mode_get_protocol_mode(packet), 0,
                       NULL, NULL, 0);
            break;
        case HIDS_SUBEVENT_SET_REPORT: {
            uint8_t type = hids_subevent_set_report_get_report_type(packet);
            uint8_t id = hids_subevent_set_report_get_report_id(packet);
            uint8_t length = hids_subevent_set_report_get_report_length(packet);
            const uint8_t *data = hids_subevent_set_report_get_report_data(packet);
            if (type == HID_REPORT_TYPE_OUTPUT) {
                if (length > 0) leds = data[0];
                send_event(DEBONAIR_EVENT_OUTPUT, 0, id, NULL, data, length);
            } else if (type == HID_REPORT_TYPE_FEATURE) {
                if (length > 0) {
                    feature = data[0];
                    save_feature();
                }
                send_event(DEBONAIR_EVENT_FEATURE, 0, id, NULL, data, length);
            }
            break;
        }
        default:
            break;
        }
        break;
    default:
        break;
    }
}

/** The Target confirmed the Service Changed indication, so it rediscovers this database. */
static void att_handler(uint8_t packet_type, uint16_t channel, uint8_t *packet, uint16_t size) {
    (void)channel;
    (void)size;
    if (packet_type != HCI_EVENT_PACKET) return;
    if (hci_event_packet_get_type(packet) != ATT_EVENT_HANDLE_VALUE_INDICATION_COMPLETE) return;
    if (att_event_handle_value_indication_complete_get_conn_handle(packet) == connection &&
        att_event_handle_value_indication_complete_get_attribute_handle(packet) == debonair_service_changed_handle &&
        att_event_handle_value_indication_complete_get_status(packet) == ERROR_CODE_SUCCESS) {
        save_database();
    }
}

static void copy_text(char *to, size_t capacity, const char *from) {
    size_t length = strlen(from);
    if (length >= capacity) length = capacity - 1;
    memcpy(to, from, length);
    to[length] = 0;
}

int debonair_hid_start(const debonair_hid_config *config, void *emit_context, debonair_emit callback) {
    if (!(config->devices & (DEBONAIR_KEYBOARD | DEBONAIR_MOUSE))) return -1;
    if (config->descriptor_length > DESCRIPTOR_BYTES) return -1;
    if (config->name_length == 0 || config->name_length > NAME_BYTES) return -1;
    context = emit_context;
    emit = callback;
    memcpy(name, config->name, config->name_length);
    name_length = config->name_length;
    memcpy(descriptor, config->descriptor, config->descriptor_length);
    copy_text(manufacturer, sizeof manufacturer, config->manufacturer);
    copy_text(model, sizeof model, config->model);
    copy_text(firmware, sizeof firmware, config->firmware);

    const uint8_t *database;
    uint16_t report_count;
    switch (config->devices) {
    case DEBONAIR_KEYBOARD:
        database = debonair_db_keyboard;
        report_count = 3;
        appearance = 0x03c1;
        break;
    case DEBONAIR_MOUSE:
        database = debonair_db_mouse;
        report_count = 2;
        appearance = 0x03c2;
        break;
    default:
        database = debonair_db_combined;
        report_count = 5;
        appearance = 0x03c0;
        break;
    }

    l2cap_init();
    sm_init();
    debonair_hid_set_security(config->passkey);
    att_server_init(database, att_read, att_write);
    // Saved subscriptions are replayed only into the database they were made in.
    const uint8_t *hash = database_hash();
    debonair_bonds_keep_subscriptions(hash, hash ? 16 : 0);
    att_server_register_packet_handler(att_handler);
    battery_service_server_init(config->battery);
    device_information_service_server_init();
    device_information_service_server_set_manufacturer_name(manufacturer);
    device_information_service_server_set_model_number(model);
    device_information_service_server_set_firmware_revision(firmware);
    // Vendor ID source 2: a USB-IF vendor ID.
    device_information_service_server_set_pnp_id(2, config->vendor_id, config->product_id, 0x0100);
    hids_device_init_with_storage(0, descriptor, config->descriptor_length, report_count, reports);
    hids_device_register_packet_handler(handler);
    hids_device_register_get_report_callback(get_report);

    // Each device combination has its own identity, so Targets pair with it as a separate device.
    bd_addr_t identity;
    memcpy(identity, config->identity, 6);
    gap_random_address_set(identity);
    bd_addr_t none = {0};
    // Connectable undirected advertising every 30 ms on all channels.
    gap_advertisements_set_params(0x0030, 0x0030, 0, 0, none, 0x07, 0);
    update_advertising();
    gap_advertisements_enable(1);

    hci_registration.callback = handler;
    hci_add_event_handler(&hci_registration);
    sm_registration.callback = handler;
    sm_add_event_handler(&sm_registration);
    return hci_power_control(HCI_POWER_ON);
}

int debonair_hid_set_name(const char *text, uint16_t length) {
    if (length == 0 || length > NAME_BYTES) return -1;
    memcpy(name, text, length);
    name_length = length;
    update_advertising();
    return 0;
}

void debonair_hid_set_security(uint8_t passkey) {
    passkey_mode = passkey != 0;
    sm_set_io_capabilities(passkey_mode ? IO_CAPABILITY_KEYBOARD_ONLY : IO_CAPABILITY_NO_INPUT_NO_OUTPUT);
    // MITM protection makes the Target enter the passkey rather than fall back to Just Works.
    sm_set_authentication_requirements(SM_AUTHREQ_SECURE_CONNECTION | SM_AUTHREQ_BONDING |
                                       (passkey_mode ? SM_AUTHREQ_MITM_PROTECTION : 0));
}

void debonair_hid_set_pairing(bool enabled) {
    if (pairing == enabled) return;
    pairing = enabled;
    update_advertising();
}

int debonair_hid_passkey(int accept, uint32_t passkey) {
    if (connection == HCI_CON_HANDLE_INVALID) return -1;
    if (accept) sm_passkey_input(connection, passkey);
    else sm_bonding_decline(connection);
    return 0;
}

int debonair_hid_disconnect(void) {
    if (connection == HCI_CON_HANDLE_INVALID) return -1;
    return gap_disconnect(connection);
}

int debonair_hid_targets(uint8_t *out, int capacity) {
    int count = 0;
    int max = le_device_db_max_count();
    for (int i = 0; i < max && count < capacity; i++) {
        int type = BD_ADDR_TYPE_UNKNOWN;
        bd_addr_t address;
        le_device_db_info(i, &type, address, NULL);
        if (type == BD_ADDR_TYPE_UNKNOWN) continue;
        out[count * 7] = (uint8_t)type;
        memcpy(&out[count * 7 + 1], address, 6);
        count++;
    }
    return count;
}

int debonair_hid_max_targets(void) { return le_device_db_max_count(); }

int debonair_hid_forget(uint8_t address_type, const uint8_t *target) {
    int max = le_device_db_max_count();
    for (int i = 0; i < max; i++) {
        int type = BD_ADDR_TYPE_UNKNOWN;
        bd_addr_t address;
        le_device_db_info(i, &type, address, NULL);
        if (type == BD_ADDR_TYPE_UNKNOWN || (type & 1) != (address_type & 1) || memcmp(address, target, 6) != 0) {
            continue;
        }
        if (connection != HCI_CON_HANDLE_INVALID && sm_le_device_index(connection) == i) {
            gap_disconnect(connection);
        }
        // Also clears the ATT server's saved subscriptions and the controller's resolving list.
        gap_delete_bonding((bd_addr_type_t)type, address);
        send_event(DEBONAIR_EVENT_TARGETS_CHANGED, 0, 0, NULL, NULL, 0);
        return 0;
    }
    return -1;
}

void debonair_hid_set_battery(uint8_t level) { battery_service_server_set_battery_value(level); }

int debonair_hid_can_send(void) {
    if (connection == HCI_CON_HANDLE_INVALID || !encrypted) return 0;
    if (att_server_can_send_packet_now(connection)) return 1;
    if (!send_requested) {
        send_requested = true;
        hids_device_request_can_send_now_event(connection);
    }
    return 0;
}

int debonair_hid_send(uint8_t channel, uint8_t report_id, const uint8_t *data, uint16_t length) {
    if (connection == HCI_CON_HANDLE_INVALID || !encrypted) return -1;
    switch (channel) {
    case DEBONAIR_CHANNEL_BOOT_KEYBOARD:
        return hids_device_send_boot_keyboard_input_report(connection, data, length);
    case DEBONAIR_CHANNEL_BOOT_MOUSE:
        return hids_device_send_boot_mouse_input_report(connection, data, length);
    default:
        break;
    }
    uint8_t *last = report_id == 1 ? last_keyboard : report_id == 2 ? last_mouse : report_id == 3 ? last_consumer : NULL;
    if (last) {
        size_t capacity = report_id == 1 ? sizeof last_keyboard : report_id == 2 ? sizeof last_mouse : sizeof last_consumer;
        memset(last, 0, capacity);
        memcpy(last, data, btstack_min(length, capacity));
        // A read of the mouse report returns held buttons only; motion is relative.
        if (report_id == 2) memset(&last_mouse[1], 0, sizeof last_mouse - 1);
    }
    return hids_device_send_input_report_for_id(connection, report_id, data, length);
}
